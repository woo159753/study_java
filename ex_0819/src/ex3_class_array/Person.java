package ex3_class_array;

public class Person {
    
    private int age;
    private String name;

    //자동완성 기능 우클릭(Sorce Acction) -> (generate getter setter ..) -> (체크 박스에 생성할 변수 설정)
    public int getAge() {
        return age;
    }
    public void setAge(int age) {
        this.age = age;
    }
    public String getName() {
        return name;
    }
    public void setName(String name) {
        this.name = name;
    }
    
    
}
